/**
 * IPSC Score Service Worker
 *
 * Handles:
 * - App shell caching (cache-first for static assets)
 * - Fetch routing (network-first for API, cache-first for assets)
 * - Background Sync trigger for pending score saves
 */

const CACHE_NAME = 'ipscscore-shell-v3';

/** How long to wait for a network fetch before falling back to cache (ms) */
const NETWORK_TIMEOUT_MS = 3_000;

// App shell assets to pre-cache on install
const APP_SHELL = [];

// File extensions that indicate immutable hashed assets
const IMMUTABLE_EXTENSIONS = ['.js', '.css', '.woff2', '.woff', '.ttf', '.eot'];

// Install: pre-cache app shell
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then(async (cache) => {
      // Try to load the precache manifest generated by the build
      try {
        const manifestResponse = await fetch('/precache-manifest.json');
        const manifest = await manifestResponse.json();
        await cache.addAll(manifest);
      } catch {
        // Manifest not available (dev mode or build issue) — cache minimal shell
        await cache.addAll(APP_SHELL).catch(() => {});
      }
    })
  );
  // Activate immediately without waiting for existing pages to close
  self.skipWaiting();
});

// Activate: clean up old caches
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames
          .filter((name) => name !== CACHE_NAME)
          .map((name) => caches.delete(name))
      );
    })
  );
  // Take control of all pages immediately
  self.clients.claim();
});

// Fetch: route requests to appropriate strategy
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);

  // Only handle same-origin requests
  if (url.origin !== self.location.origin) return;

  // API requests: skip SW interception entirely.
  // The main app handles offline fallback via IndexedDB.
  // By NOT calling event.respondWith(), the fetch goes directly to the
  // browser's network stack and the page's own AbortController manages it.
  if (url.pathname.startsWith('/api/')) {
    return;
  }

  // Immutable assets (hashed JS/CSS): cache-first, they never change
  const isImmutable = IMMUTABLE_EXTENSIONS.some((ext) => url.pathname.endsWith(ext));
  if (isImmutable && url.pathname.startsWith('/assets/')) {
    event.respondWith(cacheFirst(event.request));
    return;
  }

  // HTML navigation: stale-while-revalidate — return cached immediately,
  // then refresh in background. Avoids the old network-first hang on
  // cold-start when offline.
  if (event.request.mode === 'navigate') {
    event.respondWith(staleWhileRevalidate(event.request));
    return;
  }

  // Other static assets (icons, manifest, etc.): cache-first
  if (url.pathname.startsWith('/icons/') || url.pathname.startsWith('/favicon')) {
    event.respondWith(cacheFirst(event.request));
    return;
  }

  // Everything else: network-first with timeout
  event.respondWith(networkFirst(event.request));
});

// Background Sync: trigger pending save sync
self.addEventListener('sync', (event) => {
  if (event.tag === 'ipscscore-sync-scores') {
    event.waitUntil(
      // Notify all clients to run the sync
      self.clients.matchAll().then((clients) => {
        clients.forEach((client) => {
          client.postMessage({ type: 'TRIGGER_SYNC' });
        });
      })
    );
  }
});

// Message handler: receive messages from main thread
self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }

  if (event.data?.type === 'GET_CACHE_SIZE') {
    caches.open(CACHE_NAME).then((cache) => {
      cache.keys().then((keys) => {
        event.ports[0]?.postMessage({ type: 'CACHE_SIZE', size: keys.length });
      });
    });
  }
});

// ── Caching Strategies ──────────────────────────────────────────────────────

/**
 * Cache-first: return from cache immediately; if not in cache, fetch from
 * the network with a short timeout.
 */
async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  try {
    const response = await fetchWithTimeout(request, NETWORK_TIMEOUT_MS);
    if (response.ok) {
      const cache = await caches.open(CACHE_NAME);
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    return new Response('Offline', { status: 503, statusText: 'Service Unavailable' });
  }
}

/**
 * Stale-while-revalidate: return cached immediately (if available), then
 * fetch from the network in the background to refresh the cache.
 *
 * If not cached, falls back to the network (with short timeout).
 * If offline, returns the cached response or a 503.
 */
async function staleWhileRevalidate(request) {
  const cached = await caches.match(request);
  if (cached) {
    // Background refresh — non-blocking
    fetchWithTimeout(request, NETWORK_TIMEOUT_MS)
      .then((response) => {
        if (response.ok) {
          caches.open(CACHE_NAME).then((cache) => cache.put(request, response));
        }
      })
      .catch(() => {});
    return cached;
  }

  // Not cached at all — try the network
  try {
    const response = await fetchWithTimeout(request, NETWORK_TIMEOUT_MS);
    if (response.ok) {
      const cache = await caches.open(CACHE_NAME);
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    return new Response('Offline', { status: 503, statusText: 'Service Unavailable' });
  }
}

/**
 * Network-first with timeout: try the network within NETWORK_TIMEOUT_MS;
 * on failure or timeout, fall back to cache.
 *
 * When the device is known-offline, skip the network attempt entirely
 * to avoid the 30s+ hang Safari exhibits on failed fetches.
 */
async function networkFirst(request) {
  if (!navigator.onLine) {
    const cached = await caches.match(request);
    if (cached) return cached;
    return new Response('Offline', { status: 503, statusText: 'Service Unavailable' });
  }

  try {
    const response = await fetchWithTimeout(request, NETWORK_TIMEOUT_MS);
    if (response.ok) {
      const cache = await caches.open(CACHE_NAME);
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    const cached = await caches.match(request);
    if (cached) return cached;
    return new Response('Offline', { status: 503, statusText: 'Service Unavailable' });
  }
}

/**
 * Fetch with an AbortController timeout. Rejects if the response does not
 * arrive within `timeoutMs`.
 */
async function fetchWithTimeout(request, timeoutMs) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    return await fetch(request, { signal: controller.signal });
  } finally {
    clearTimeout(timer);
  }
}